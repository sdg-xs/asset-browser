export const ifcClassSnapshot: ClassificationOption[] = entries.map(([code, name]) => ({ value: code.toUpperCase(), label: code, description: name }));

const classLabels = new Map(ifcClassSnapshot.map(option => [option.value, option.label]));
export function ifcClassLabel(value: string): string {
  const code = value.toUpperCase();
  const label = classLabels.get(code);
  if (label) return label;
  for (const suffix of ["Type", "Style"]) {
    if (code.endsWith(suffix.toUpperCase())) {
      const base = classLabels.get(code.slice(0, -suffix.length));
      if (base) return base + suffix;
    }
  }
  return value;
}
